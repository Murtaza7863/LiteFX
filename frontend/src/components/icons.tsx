// Map a rail type to its icon (used by cards, legend, modal).
export function RailIcon({ type, className }: { type: string; className?: string }) {
  const cls = className ?? "h-4 w-4";
  switch (type) {
    case "local":
      return <IconZap className={cls} />;
    case "linked":
      return <IconLink className={cls} />;
    case "claim_link":
      return <IconTicket className={cls} />;
    default:
      return <IconGlobe className={cls} />;
  }
}
